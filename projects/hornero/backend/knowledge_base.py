def get_system_prompt_rag(formato: str, chunk_ids: list = None, clipping_items: list = None, query: str = "", requested_persona: str = "", grade: str = "A", incoming_reports: list = None, recipient_chain: str = "") -> str:
    """Return system prompt with selective KB injection based on RAG retrieval.

    Only includes KB chunks relevant to the user's query, not the entire KB.
    This reduces token usage by 60-80% per request.

    Args:
        formato: section/persona (debate, consulta, contenido, reporte)
        chunk_ids: list of KB chunk IDs to inject (from rag_retriever)
        clipping_items: dynamic clipping data (all or filtered)
        query: user query text (for clipping filtering in Phase 2)
        requested_persona: explicit persona override (companero/abogado/periodista/historiador)
        grade: user grade (A, B.a, B.b, B.c, B.d) — affects Compañero behavior
        incoming_reports: list of incoming reports from lower grades (for G2+ users)
    """

    # Determine effective formato based on requested_persona override
    effective_formato = formato
    if requested_persona and requested_persona in PERSONA_NAME_MAP:
        effective_formato = PERSONA_NAME_MAP[requested_persona]

    personas = {
        'debate': PERSONA_DEBATE,
        'consulta': PERSONA_CONSULTA,
        'contenido': PERSONA_CONTENIDO,
        'reporte': PERSONA_DEBATE,
        'historia': PERSONA_HISTORIADOR,
        'panorama': PERSONA_SOCIOLOGO,
        'ecosistema': PERSONA_HORNERO,
    }

    persona = personas.get(effective_formato, PERSONA_CONSULTA)  # default: abogado
    prompt = persona + "\n" + PRINCIPIOS_COMUNES

    # Inject grade context for Compañero persona (debate/reporte)
    if effective_formato in ('debate', 'reporte'):
        grade_map = {'A': 'G1', 'B.a': 'G1', 'B.b': 'G2', 'B.c': 'G3', 'B.d': 'G4'}
        grade_code = grade_map.get(grade, 'G1')
        grade_role_map = {
            'G1': 'TRABAJADOR/A DE BASE — tu función es reportar tu situación.',
            'G2': 'DELEGADO/A — tu función principal es revisar reportes G1 de los trabajadores de base y elaborar reporte G2.',
            'G3': 'SECRETARIO/A — tu función principal es revisar reportes G2 de los delegados y elaborar reporte G3.',
            'G4': 'FEDERACIÓN — tu función principal es revisar reportes G3 y elaborar reporte G4.',
        }
        grade_role = grade_role_map.get(grade_code, grade_role_map['G1'])
        prompt += f"\n\n=== CONTEXTO DEL USUARIO ===\nGrado: {grade} ({grade_code})\nRol: {grade_role}"
        if recipient_chain:
            prompt += f"\nCadena de destinatarios: {recipient_chain}"

    # Inject incoming reports ONLY for Compañero persona (debate/reporte)
    # CRITICAL PRIVACY: reporte gremial content is CONFIDENTIAL — never expose to other personas
    if incoming_reports and len(incoming_reports) > 0 and effective_formato in ('debate', 'reporte'):
        reports_text = get_incoming_reports_text(incoming_reports)
        if reports_text:
            prompt += "\n\n" + reports_text

    # Inject only relevant chunks
    if chunk_ids:
        chunks_text = get_chunks_text(chunk_ids)
        if chunks_text:
            prompt += "\n\n" + chunks_text
    else:
        # No specific chunks matched — include topic guide so IA knows what it can discuss
        available_topics = ", ".join(set(c["category"] for c in KB_CHUNKS))
        prompt += f"\n\nTEMAS DISPONIBLES: {available_topics}. Si la pregunta no coincide con ninguno, respondé lo que puedas y sugerí temas relacionados."

    # Add dynamic clipping if available
    if clipping_items:
        clipping_text = get_clipping_text(clipping_items)
        if clipping_text:
            prompt += "\n\n" + clipping_text

    return prompt


def get_incoming_reports_text(reports: list) -> str:
    """Format incoming reports from lower grades for system prompt injection.

    Each report formatted with FULL section content + correcciones.
    Includes rules for the Compañero to synthesize these reports.
    """
    if not reports:
        return ""

    lines = ["=== REPORTES ENTRANTES (para revisión) ===", ""]
    lines.append("Tenés acceso al contenido COMPLETO de estos reportes. Podés citarlos, referenciarlos, y hacer síntesis de ellos.")
    lines.append("")

    for report in reports:
        report_id = report.get("id", "sin-id")
        numero = report.get("numero", "")
        estado = report.get("estado", "pendiente")
        source_grade = report.get("grado", "")
        username = report.get("username", "")
        fecha = report.get("fecha", "")

        # Header
        header = f"--- REPORTE {report_id}"
        if numero:
            header += f" N°{numero}"
        header += f" | Estado: {estado}"
        if source_grade:
            header += f" | Grado origen: G{source_grade}"
        if username:
            header += f" | Autor: @{username}"
        if fecha:
            header += f" | Fecha: {fecha}"
        header += " ---"
        lines.append(header)

        # Full sections
        sections = report.get("sections", [])
        for sec in sections:
            sec_title = sec.get("title", "")
            sec_body = sec.get("body", "")
            if sec_title:
                lines.append(f"  [{sec_title}]")
            if sec_body:
                # Indent body for readability
                for body_line in sec_body.split("\n"):
                    lines.append(f"    {body_line}")

        # Correcciones (modifications)
        correcciones = report.get("correcciones", [])
        if correcciones:
            lines.append("  [Correcciones]")
            for corr in correcciones:
                corr_tipo = corr.get("tipo", "")
                corr_grado = corr.get("correctorGrado", "")
                corr_user = corr.get("correctorUsername", "")
                corr_seccion = corr.get("seccionTitle", "")
                corr_resumen = corr.get("resumen", "")
                corr_texto = corr.get("textoNuevo", "")
                corr_line = f"    - G{corr_grado} (@{corr_user}): {corr_tipo}"
                if corr_seccion:
                    corr_line += f" en '{corr_seccion}'"
                if corr_resumen:
                    corr_line += f" — {corr_resumen}"
                lines.append(corr_line)
                if corr_texto and corr_tipo in ("modificado", "agregado"):
                    # Full text needed for synthesis — no truncation
                    lines.append(f"      Texto nuevo: {corr_texto}")

        lines.append("")  # blank line between reports

    lines.append("REGLAS DE SÍNTESIS:")
    lines.append("1. Tu función principal es revisar estos reportes y elaborar un reporte de tu grado (G2/G3/G4) basado en ellos.")
    lines.append("2. Para elaborar el reporte, sintetizá los reportes entrantes: identificá temas comunes, patrones, situaciones que se repiten, y elaborá un informe consolidado.")
    lines.append("3. Si hay correcciones/modificaciones en los reportes, tenélas en cuenta para la síntesis — el texto modificado reemplaza al original.")
    lines.append("4. Preguntá si el usuario los leyó y trabajá sobre ellos. Si insiste en reportar algo propio, marcá que es ad hoc y procedé con el flujo normal.")

    return "\n".join(lines)


def get_clipping_text(items: list) -> str:
    """Format clipping items as text for system prompt injection.

    Each item formatted as: [NOTICIA: titulo — bajada. Fuente: fuente, Fecha: fecha]
    Includes citation rule to force source attribution.
    """
    if not items:
        return ""

    lines = ["=== NOTICIAS ACTUALES (Clipping Hornero) ===", ""]

    for item in items:
        titulo = item.get("titulo", "").strip()
        bajada = item.get("bajada", "").strip()
        fuente = item.get("fuente", "").strip()
        fecha = item.get("fecha", "").strip()
        tags = ", ".join(item.get("tags", [])[:5])

        if not titulo:
            continue

        # Format: concise noticia entry
        entry = f"[NOTICIA: {titulo}"
        if bajada:
            # Truncate bajada to ~80 chars for token efficiency
            short_bajada = bajada[:80] + "..." if len(bajada) > 80 else bajada
            entry += f" — {short_bajada}"
        entry += f". Fuente: {fuente}, Fecha: {fecha}]"
        if tags:
            entry += f" Tags: {tags}"
        # Include image and source URL if available
        foto = item.get("foto", "").strip()
        fuente_url = item.get("fuente_url", "").strip()
        if foto:
            entry += f" Foto: {foto}"
        if fuente_url:
            entry += f" URL: {fuente_url}"
        lines.append(entry)

    lines.append("")
    lines.append("REGLA DE CITACIÓN: Si usás datos de estas noticias, SIEMPRE citá la fuente visible: \"Fuente: Sonido Gremial, 2 de julio\" o \"Según InfoGremiales del 30 de junio\". Si la noticia no está en esta lista, no la mencionás.")
    lines.append("REGLA DE IMAGEN: Si la noticia que estás comentando tiene Foto, incluí SIEMPRE la URL en el campo \"image\" de tu JSON o section. Si tiene URL, incluíla en \"source_url\". El trabajador ve la imagen directamente en el chat.")

    return "\n".join(lines)


