def get_system_prompt_rag(formato: str, chunk_ids: list = None, clipping_items: list = None, query: str = "", requested_persona: str = "", grade: str = "A", incoming_reports: list = None, recipient_chain: str = "", extra_sources_text: str = "", tenant: str = "aceiteros", relevant_clipping: list = None) -> str:
    """Return system prompt with selective KB injection based on RAG retrieval.

    Only includes KB chunks relevant to the user's query, not the entire KB.
    This reduces token usage by 60-80% per request.

    Args:
        formato: section/persona (debate, consulta, contenido, reporte)
        chunk_ids: list of KB chunk IDs to inject (from rag_retriever)
        clipping_items: dynamic clipping data (all or filtered)
        query: user query text (for clipping filtering in Phase 2)
        requested_persona: explicit persona override (companero/abogado/periodista/historiador)
        grade: user grade (A, B.a, B.b, B.c, B.d) — affects Compañero behavior
        incoming_reports: list of incoming reports from lower grades (for G2+ users)
        tenant: tenant key for sector profile injection (aceiteros, prensa, etc.)
    """

    # Determine effective formato based on requested_persona override
    effective_formato = formato
    if requested_persona and requested_persona in PERSONA_NAME_MAP:
        effective_formato = PERSONA_NAME_MAP[requested_persona]

    personas = {
        'debate': PERSONA_DEBATE,
        'consulta': PERSONA_CONSULTA,
        'contenido': PERSONA_CONTENIDO,
        'reporte': PERSONA_DEBATE,
        'historia': PERSONA_HISTORIADOR,
        'panorama': PERSONA_SOCIOLOGO,
        'ecosistema': PERSONA_HORNERO,
    }

    persona = personas.get(effective_formato, PERSONA_CONSULTA)  # default: abogado

    # Inject TU GREMIO block after persona, before examples + PRINCIPIOS_COMUNES
    sector_context = get_sector_context(tenant)
    prompt_parts = [persona, sector_context]

    # Inject persona-specific examples (shows HOW to respond, not just rules)
    examples = _get_persona_examples(effective_formato)
    if examples:
        prompt_parts.append(examples)

    prompt_parts.append(PRINCIPIOS_COMUNES)
    prompt = "\n".join(prompt_parts)

    # Inject relevant clipping items (filtered by query) — BEFORE chunks so LLM sees them first
    # These are clipping items whose tags/title/bajada match the user's query,
    # presented prominently so the LLM doesn't miss them in the long full-clipping section
    if relevant_clipping:
        from rag_retriever import clipping_search  # avoid circular import
        clip_lines = [
            "=== NOTICIAS RELEVANTES A TU CONSULTA (del Clipping Hornero) ===",
            "Estas noticias del clipping están directamente relacionadas con lo que el trabajador pregunta. USALAS primero — citá siempre la fuente y fecha:",
            ""
        ]
        for item in relevant_clipping:
            titulo = item.get("titulo", "").strip()
            bajada = item.get("bajada", "").strip()
            fuente = item.get("fuente", "").strip()
            fecha = item.get("fecha", "").strip()
            tags = ", ".join(item.get("tags", [])[:5])
            foto = item.get("foto", "").strip()
            fuente_url = item.get("fuente_url", "").strip()
            entry = f"[NOTICIA: {titulo}"
            if bajada:
                short_bajada = bajada[:150] + "..." if len(bajada) > 150 else bajada
                entry += f" — {short_bajada}"
            entry += f". Fuente: {fuente}, Fecha: {fecha}]"
            if tags:
                entry += f" Tags: {tags}"
            if foto:
                entry += f" Foto: {foto}"
            if fuente_url:
                entry += f" URL: {fuente_url}"
            clip_lines.append(entry)
        clip_lines.append("")
        prompt += "\n\n" + "\n".join(clip_lines)

    # Inject grade context for Compañero persona (debate/reporte)
    if effective_formato in ('debate', 'reporte'):
        grade_map = {'A': 'G1', 'B.a': 'G1', 'B.b': 'G2', 'B.c': 'G3', 'B.d': 'G4'}
        grade_code = grade_map.get(grade, 'G1')
        grade_role_map = {
            'G1': 'TRABAJADOR/A DE BASE — tu función es reportar tu situación.',
            'G2': 'DELEGADO/A — tu función principal es revisar reportes G1 de los trabajadores de base y elaborar reporte G2.',
            'G3': 'SECRETARIO/A — tu función principal es revisar reportes G2 de los delegados y elaborar reporte G3.',
            'G4': 'FEDERACIÓN — tu función principal es revisar reportes G3 y elaborar reporte G4.',
        }
        grade_role = grade_role_map.get(grade_code, grade_role_map['G1'])
        prompt += f"\n\n=== CONTEXTO DEL USUARIO ===\nGrado: {grade} ({grade_code})\nRol: {grade_role}"
        if recipient_chain:
            prompt += f"\nCadena de destinatarios: {recipient_chain}"

    # Inject incoming reports ONLY for Compañero persona (debate/reporte)
    # CRITICAL PRIVACY: reporte gremial content is CONFIDENTIAL — never expose to other personas
    if incoming_reports and len(incoming_reports) > 0 and effective_formato in ('debate', 'reporte'):
        reports_text = get_incoming_reports_text(incoming_reports)
        if reports_text:
            prompt += "\n\n" + reports_text

    # Inject only relevant chunks
    if chunk_ids:
        chunks_text = get_chunks_text(chunk_ids)
        if chunks_text:
            prompt += "\n\n" + chunks_text
    else:
        # No specific chunks matched — include topic guide so IA knows what it can discuss
        available_topics = ", ".join(set(c["category"] for c in KB_CHUNKS))
        prompt += f"\n\nTEMAS DISPONIBLES: {available_topics}. Si la pregunta no coincide con ninguno, respondé lo que puedas y sugerí temas relacionados."

    # Inject documents catalog:
    # - ALWAYS for Historiadora (historia formato) — she manages the archive
    # - For other personas, only when query contains legal/doc keywords
    if effective_formato == 'historia':
        prompt += "\n\n" + get_documentos_catalog_text(tenant)
    elif query:
        doc_keywords = ["ley", "leyes", "convenio", "convenios", "cct", "paritaria",
                        "paritarias", "documento", "documentos", "legislación",
                        "legislacion", "laboral", "normativa", "reglamento",
                        "estatuto", "código", "codigo", "acuerdo", "acta",
                        "qué leyes", "que leyes", "qué documentos", "que documentos",
                        "listado", "catálogo", "catalogo"]
        query_lower = query.lower()
        if any(kw in query_lower for kw in doc_keywords):
            prompt += "\n\n" + get_documentos_catalog_text(tenant)

    # Add dynamic clipping if available
    # For consulta (Abogado): clipping is context-only, not citable as legal source
    if clipping_items:
        clipping_text = get_clipping_text(clipping_items)
        if clipping_text:
            if effective_formato == 'consulta':
                prompt += "\n\n=== NOTICIAS ACTUALES (CONTEXTO INFORMATIVO — NO son fuentes legales) ==="
                prompt += "\nEstas noticias son para tu conocimiento del panorama actual. NO las cites como fuente en tu respuesta legal. Podés mencionarlas al final solo como referencia contextual: 'En la prensa se menciona que...' Tu fundamento es siempre la ley, el convenio y la doctrina.\n\n"
            else:
                prompt += "\n\n"
            prompt += clipping_text

    # Inject MATE (InfoMate) data for Investigador (panorama) persona
    if effective_formato == 'panorama':
        try:
            from mate_cache import get_mate
            mate_editions = get_mate()
            if mate_editions:
                mate_text = get_mate_text(mate_editions)
                if mate_text:
                    prompt += "\n\n" + mate_text
        except Exception as e:
            print(f"MATE data injection failed: {e}")

    # Inject external legal sources (Biblioteca Hornero) — solo si el puente las trae.
    # Va AL FINAL a propósito (recencia): es lo último que lee el modelo antes de responder,
    # así prioriza los artículos exactos por sobre su conocimiento previo.
    # Aditivo y reversible: si extra_sources_text == "" el prompt es idéntico al de antes.
    if extra_sources_text:
        prompt += "\n\n" + extra_sources_text

    return prompt


