def get_greeting_hint(section: str, grade: str = 'A', days_since_last_chat: int = 999, incoming_reports_count: int = 0) -> str:
    """Prompt for the IA's opening message — BRIEF, persona-specific, one question.

    CRITICAL: The greeting must be 2-3 lines max. Persona presents herself,
    asks what the user wants. NO data dumps, NO topic lists, NO quotes.

    For higher grades (B.b, B.c, B.d) in reporte section: also asks about
    pending incoming reports to review.

    days_since_last_chat affects greeting tone:
    - 0 (same day): acknowledge return, brief "volviste"
    - 1-7 (same week): casual "como andás esta semana"
    - 8+ (longer): warmer "hace tiempo, como andás"
    """
    grade_map = {'A': 'G1', 'B.a': 'G1', 'B.b': 'G2', 'B.c': 'G3', 'B.d': 'G4'}
    grade_code = grade_map.get(grade, 'G1')
    is_higher_grade = grade_code in ('G2', 'G3', 'G4')

    # Time-aware greeting context
    time_context = ""
    if days_since_last_chat == 0:
        time_context = " CONTEXTO: Volvieron a hablar hoy mismo — saluda como un regreso breve, no como si hace tiempo. Ejemplo: '¡Volviendo! ¿Qué más querés reportar?' — NO digas 'hace un par de días' o 'hace tiempo'."
    elif days_since_last_chat <= 7:
        time_context = " CONTEXTO: Charlaste esta semana — saluda casual como si hablan seguido. Ejemplo: '¿Cómo andás esta semana?' — NO digas 'hace tiempo' o 'hace un par de días'."
    elif days_since_last_chat <= 30:
        time_context = " CONTEXTO: Hace un par de semanas — saluda reconociendo la ausencia pero brevemente. Ejemplo: '¿Cómo andás? Hace un par de semanas que no charlamos.'"
    else:
        time_context = " CONTEXTO: Hace tiempo que no charlan — saluda reconociendo la ausencia. Ejemplo: '¡Qué bueno verte! Hace tiempo que no hablamos.'"

    greetings = {
        'debate': 'Saluda brevemente (2-3 líneas). Di que sos un compañero del gremio con años de experiencia en planta. Preguntá qué tema quiere debatir. NO cites datos, NO列举 temas, NO expliques todo. Solo saludá + quién sos + una pregunta. MODO CHARLA — {"sections": [{"title": "", "body": "..."}], "tags": ["debate", "saludo"]}',

        'consulta': 'Saluda brevemente (2-3 líneas). Di que sos abogado laboralista del gremio. Preguntá qué consulta legal tiene. NO cites fallos, NO expliques el marco legal, NO列举 derechos. Solo saludá + quién sos + una pregunta. MODO CHARLA — {"sections": [{"title": "", "body": "..."}], "tags": ["consulta", "saludo"]}',

        'contenido': 'Saluda brevemente (2-3 lines). Di que sos periodista que ayuda al gremio y a sus trabajadores. Pregunta que formato le interesa o que tema quiere comunicar. NO lista formatos detallados, NO expliques todo lo que puedes hacer. Solo saluda + quien sos + una pregunta. MODO CHARLA — {"sections": [{"title": "", "body": "..."}], "tags": ["contenido", "saludo"]}',

        'reporte': 'Saluda brevemente (2-3 lines). Pregunta como andaron los ultimos dias, si hay alguna situacion que quiera reportar — condiciones, seguridad, ritmo, algo que le paso o que vio. NO expliques el sistema de informes, NO lista temas. Solo saluda + una pregunta. MODO CHARLA — {"sections": [{"title": "", "body": "..."}], "tags": ["reporte", "saludo"]}',

        'historia': 'Saluda brevemente (2-3 líneas). Di que sos historiadora del movimiento obrero argentino — conoces La Forestal, las masacres, los lockouts, los referentes que nadie recuerda. Preguntá qué tema histórico quiere explorar. NO cites datos, NO列举 eventos, NO quotes en el saludo. Solo saludá + quién sos + una pregunta. MODO CHARLA — {"sections": [{"title": "", "body": "..."}], "tags": ["historia", "saludo"]}',

        'panorama': 'Saluda brevemente (2-3 líneas). Di que sos investigador/a de la clase obrera — estudiás cómo se forma la clase trabajadora, qué la compone, qué la daña y qué la sostiene. Preguntá qué quiere explorar. NO cites datos, NO列举 índices, NO expliques todo. Solo saludá + quién sos + una pregunta. MODO CHARLA — {"sections": [{"title": "", "body": "..."}], "tags": ["panorama", "saludo"]}',

        'ecosistema': 'Saluda brevemente (2-3 líneas). Di que sos Hornero — el pájaro que construye su propio nido. La organización no consume IA corporativa, crea su propia herramienta. Preguntá qué quiere saber sobre el ecosistema. NO expliques los 6 eslabones, NO列举 temas, NO cites datos en el saludo. Solo saludá + quién sos + una pregunta. MODO CHARLA — {"sections": [{"title": "", "body": "..."}], "tags": ["ecosistema", "saludo"]}',
    }

    # For higher grades in reporte: primary function is reviewing incoming reports
    if is_higher_grade and section == 'reporte':
        role_names = {'G2': 'delegado/a', 'G3': 'secretario/a', 'G4': 'de la federación'}
        role_name = role_names.get(grade_code, 'delegado/a')
        reports_mention = f" Tenés {incoming_reports_count} reportes de compañeros pendientes de revisión." if incoming_reports_count > 0 else ""
        greetings['reporte'] = f'Saluda brevemente (2-3 lines). Como {role_name}, tu función principal es revisar los reportes de los compañeros.{reports_mention} Pregunta si ya reviso los reportes entrantes o si quiere revisarlos ahora para elaborar su informe. Si no tiene reportes para revisar, pregunta si quiere reportar algo propio. NO expliques el sistema, NO lista temas. Solo saluda + pregunta sobre reportes entrantes. MODO CHARLA — {{"sections": [{{"title": "", "body": "..."}}], "tags": ["reporte", "saludo", "grado-superior"]}}'

    return greetings.get(section, greetings['consulta']) + time_context
